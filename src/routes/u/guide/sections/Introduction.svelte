	<h2 id="introduction">Introduction</h2>

	<h3 id="about-citeticket">About CiteTicket</h3>
	<p>
		<strong>CiteTicket</strong> (Citation Ticket Management System) is a web-based application for managing
		citation tickets issued by local law enforcement groups and agencies. It provides a centralized platform
		for officers to issue, track, and manage tickets efficiently — improving transparency, accountability,
		and accessibility in the citation process.
	</p>

	<h3 id="who-its-for">Who it's for</h3>
	<p>
		CiteTicket is intended for local law enforcement groups and agencies responsible for issuing
		citation tickets. It streamlines the ticketing process, improves record-keeping, and enhances
		communication between officers and the public. Specifically, it can be used by:
	</p>
	<ul class="not-prose my-4 flex flex-wrap gap-2">
		{#each ['Traffic Management Office', 'Anti-Smoking Enforcers', 'Bantay Dagat Enforcers', 'Forest Protection', 'Other local enforcement groups'] as group (group)}
			<li class="badge badge-soft badge-primary h-auto px-3 py-2 text-sm">{group}</li>
		{/each}
	</ul>

	<h3 id="whats-new">What's new</h3>
	<ul>
		<li>Enhanced user interface and experience</li>
		<li>Improved data management and reporting capabilities</li>
		<li>Features such as payment processing, billing generation, seamless issuance, and more</li>
		<li>Permissions-based access control</li>
		<li>Improved security measures and audit trails</li>
		<li>Highly configurable</li>
	</ul>

	<h3 id="system-requirements">System requirements</h3>
	<p>
		CiteTicket is a web-based application that can be accessed through modern web browsers such as
		Google Chrome, Mozilla Firefox, Microsoft Edge, and Safari. It is compatible with desktop and
		mobile devices, providing flexibility for users to access the system from anywhere with an
		internet connection.
	</p>
